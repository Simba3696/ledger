// Which store test cases the backend parity suite runs (issue #5). Every
// `it(...)` in the 8 store test files is listed here by "describe > title",
// and manifest.test.ts fails when one is added, renamed or removed without
// an entry, or when a ported case is missing from its *.parity.test.ts.
//
// A case is `sql-only` only for one of three reasons:
// - postgres-concurrency: it needs a second Postgres connection or lock.
// - database-internals: it observes identity values, positions or a
//   rollback through SQL rather than through the API.
// - store-only-arguments: it calls a store function with arguments no route
//   can send, or one no route exposes.

